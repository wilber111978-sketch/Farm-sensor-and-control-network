#!/usr/bin/env python3
"""Generate go2rtc.yaml for FarmPi from the dashboard's private .env file.

Usage: python3 make_go2rtc_config.py /opt/farm-dashboard/.env > /opt/go2rtc/go2rtc.yaml

go2rtc only relays the camera's own video to the browser (no re-encoding), so a
Raspberry Pi 3 can serve H.265/H.264 streams with almost no CPU. The config is
locked down to streaming only: no config API, no exec/echo/ffmpeg sources.
"""
import hashlib
import json
import sys
from pathlib import Path
from urllib.parse import quote


def read_env(path):
    values = {}
    for raw_line in Path(path).read_text(encoding="utf-8").splitlines():
        line = raw_line.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, value = line.split("=", 1)
        values[key.strip()] = value.strip().strip('"').strip("'")
    return values


def main():
    env_path = sys.argv[1] if len(sys.argv) > 1 else "/opt/farm-dashboard/.env"
    env = read_env(env_path)

    host = env.get("SOLAR_CAMERA_HOST", "192.168.1.100")
    user = env.get("SOLAR_CAMERA_USER", "admin")
    password = env.get("SOLAR_CAMERA_PASSWORD", "")
    rtsp_port = env.get("SOLAR_CAMERA_RTSP_PORT", "554")
    api_port = env.get("GO2RTC_PORT", "1984")
    webrtc_port = env.get("GO2RTC_WEBRTC_PORT", "8555")

    if not password:
        sys.exit("SOLAR_CAMERA_PASSWORD is empty in .env - cannot build camera streams")

    # Same token format FarmPi's app.py already uses for this camera.
    token = hashlib.md5(password.encode("utf-8")).hexdigest().upper()

    def rtsp(stream):
        return (
            f"rtsp://{host}:{rtsp_port}/{stream}"
            f"?username={quote(user, safe='')}&password={quote(token, safe='')}"
        )

    # JSON strings are valid YAML scalars, so json.dumps gives safe quoting.
    print(f"""# Generated by FarmPi/tools/make_go2rtc_config.py - do not edit by hand.
# Re-run install-go2rtc.sh after changing camera settings in .env.
app:
  # Only what live viewing needs. Leaving out exec/echo/ffmpeg means nobody
  # on the network can make go2rtc run commands.
  modules: [api, ws, rtsp, webrtc, mp4]

log:
  level: info

api:
  listen: ":{api_port}"
  origin: "*"            # dashboard page (port 5000) connects cross-port
  allow_paths: [/api/ws] # streaming only - no web UI, no config API

rtsp:
  listen: "127.0.0.1:8554"

webrtc:
  listen: ":{webrtc_port}"

streams:
  solar_sub: {json.dumps(rtsp("stream1"))}
  solar_main: {json.dumps(rtsp("stream0"))}
""")


if __name__ == "__main__":
    main()
